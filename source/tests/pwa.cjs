const http=require('http'),fs=require('fs'),path=require('path');
const L=require('./lib.cjs');const {chromium}=L;const T=L.makeT('pwa');
const ROOT=path.resolve(__dirname,'../pwa');
const mime={'.html':'text/html; charset=utf-8','.mjs':'text/javascript','.js':'text/javascript','.webmanifest':'application/manifest+json','.png':'image/png','.bcmap':'application/octet-stream','.pfb':'application/octet-stream','.ttf':'font/ttf','.wasm':'application/wasm','.icc':'application/octet-stream'};
(async()=>{
  const s=http.createServer((q,r)=>{let f=decodeURIComponent(q.url.split('?')[0]);let p=path.join(ROOT,f==='/'?'index.html':f);fs.readFile(p,(e,d)=>{if(e){r.writeHead(404);r.end()}else{r.writeHead(200,{'content-type':mime[path.extname(p)]||'application/octet-stream'});r.end(d)}})});
  await new Promise(r=>s.listen(0,r));const base='http://localhost:'+s.address().port;
  const br=await chromium.launch();
  const ctx=await br.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const pg=await ctx.newPage();const errs=[];pg.on('pageerror',e=>errs.push(e.message));
  await pg.route(u=>!u.href.startsWith(base),r=>r.abort());
  await pg.goto(base+'/');await pg.waitForSelector('.book');
  await pg.evaluate(()=>navigator.serviceWorker.ready.then(()=>1));
  await pg.waitForFunction(()=>navigator.serviceWorker.controller||false,null,{timeout:20000}).catch(async()=>{await pg.reload();await pg.waitForSelector('.book')});
  const keys=await pg.evaluate(async()=>{const ks=await caches.keys();const c=await caches.open(ks.find(k=>k.startsWith('folio-')&&k!=='folio-fonts'));return (await c.keys()).length});
  T.ok('service worker precached the app shell and PDF engine',keys>=200,keys);
  const man=await pg.evaluate(async()=>{const m=await (await fetch('manifest.webmanifest')).json();return {n:m.name,i:m.icons.length}});
  T.eq('manifest loads',man,{n:'Quill',i:3});
  await ctx.setOffline(true);
  await pg.reload();await pg.waitForSelector('.book');
  T.ok('app opens fully offline',true);
  const r=await L.importFile(pg,path.join(__dirname,'corpus/novel40.pdf'),{timeout:300000});
  T.ok('PDF import works offline (vendored pdf.js)',r.added,r);
  await pg.click('.book:not(.add):last-of-type').catch(()=>{});
  await pg.waitForSelector('#scroller .card',{timeout:20000});
  const n=await pg.evaluate(()=>document.querySelectorAll('#scroller .card').length);
  T.ok('imported book opens and paginates offline',n>10,n);
  await pg.reload();await pg.waitForSelector('.book');
  const cnt=await pg.$$eval('.book:not(.add)',e=>e.length);
  T.ok('imported book survives offline reload',cnt>=2,cnt);
  T.eq('no page errors',errs,[]);
  await br.close();s.close();T.done();
})();
